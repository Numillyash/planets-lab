"""M2: offline aggregate-only triage of the 915 surface residuals.

Input: the NEW complete baseline68 surface-context report generated by
PR #231 on the corpus server. The source sample and previously
published mineral residual 2x2 must match exactly. This code never
opens DuckDB or emits user/game/ship/planet IDs or raw state.

All percentages are DESCRIPTIVE fractions of correlated observations,
not causal or independent confidence estimates.
"""
from __future__ import annotations

from collections import Counter, defaultdict
from collections.abc import Mapping
from typing import Any

SCHEMA = "planets-lab.m2-surface-context-aggregate-triage.v1"
EXPECTED_DB_SHA = "3c9604f0691e3fa0d13c1c7d789a855f390f4c9e1df0d8ff97900cedbd064f0c"
EXPECTED_FROZEN_SAMPLE_SHA = "b6a09b95e2a8a6d261cb5d4180be45eb601711df9865cf0b44457ad17b84068f"
MINERAL_CLASSES = (
    "both_exact", "ground_exact_surface_residual",
    "surface_exact_ground_residual", "neither_exact",
)
PUBLISHED_BY_MINERAL = {
    "duranium": (2955, 226, 11, 63),
    "molybdenum": (2939, 245, 8, 64),
    "neutronium": (2976, 202, 7, 71),
    "tritanium": (2943, 242, 7, 64),
}
SELECTED_COVARIATES = (
    "planet_coordinates_qualified",
    "owner_ship_section_pair_qualified",
    "owner_ship_observed_at_site_both",
    "one_ship_opposite_cargo_delta_candidate",
    "opposite_cargo_ship_both_freshness_explicit",
    "opposite_cargo_ship_freshness_unverified",
    "owner_starbase_explicit_at_planet_both",
    "observed_starbase_tech_changed",
    "structure_and_tax_controls_qualified",
    "structure_or_tax_controls_changed",
    "ABSTAIN_PLANET_COORDS_MISSING",
    "ABSTAIN_SHIP_SECTION_MISSING_ONE_OR_BOTH",
    "ownerless_base_planetlinked_before_not_owner_proof",
    "ownerless_base_planetlinked_after_not_owner_proof",
    "ownerless_base_planetlinked_both_not_owner_proof",
    "planetlinked_base_both_any_owner_provenance",
    "planetlinked_base_owner_provenance_changed",
    "ownerless_planetlinked_tech_changed_observed",
    "ownerless_planetlinked_tech_unchanged_observed",
    "same_site_identical_ship_set_all_cargo_qualified",
    "multiple_co_site_ship_ids_all_cargo_qualified",
    "multiple_ship_cargo_sum_opposite_candidate_not_order",
)


def _require(condition: bool, reason: str):
    if not condition:
        raise ValueError(reason)


def _count(mapping: Mapping[str, Any], key: str) -> int:
    value = mapping.get(key, 0)
    _require(type(value) is int and value >= 0, "invalid aggregate nonnegative count")
    return value


def _portion(numerator: int, denominator: int) -> float | None:
    return round(100.0 * numerator / denominator, 2) if denominator else None


def analyze_surface_context_aggregate(report: Mapping[str, Any]) -> dict[str, Any]:
    _require(report.get("schema") ==
             "planets-lab.m2-public-corpus-economy-coverage.v1",
             "unexpected archive evidence schema")
    generation = report.get("generation")
    boundary = report.get("baseline_sample_allowlist")
    meta = report.get("metadata")
    limits = report.get("evidence_limits")
    _require(isinstance(generation, Mapping) and
             generation.get("verified_sha256") == EXPECTED_DB_SHA and
             generation.get("read_only") is True and
             generation.get("CURRENT_modified") is False,
             "source corpus digest/CURRENT not verified")
    _require(isinstance(boundary, Mapping) and
             boundary.get("allowed_game_count") == 68 and
             boundary.get("heldout_entity_sampling") is False,
             "baseline68/holdout boundary violated")
    _require(isinstance(meta, Mapping) and
             meta.get("metadata_frozen_selection_sha256") ==
             EXPECTED_FROZEN_SAMPLE_SHA and
             meta.get("metadata_frozen_sample_pairs") == 136 and
             meta.get("games_excluded_from_entity_sampling") == 32,
             "different frozen perspective sample")
    _require(isinstance(limits, Mapping) and all(
        limits.get(name) is False for name in (
            "NuHost_economic_formula_verified",
            "raw_trn_is_submitted_turn_orders",
            "same_site_owner_ship_observation_proves_cargo_transfer",
            "no_owner_ship_observed_excludes_ship_actions",
            "starbase_at_planet_means_ship_construction_executed",
        )
    ), "causal limits must remain explicitly false")
    sample = report.get("sample")
    _require(isinstance(sample, Mapping), "sample missing")
    context = sample.get("surface_residual_context_not_host_verified")
    mining = sample.get("conditional_mineral_mass_balance_not_host_verified")
    _require(isinstance(context, Mapping) and isinstance(mining, Mapping),
             "mineral residual and context sections required")
    classes = context.get("per_mineral_residual_classes")
    covariates = context.get("per_mineral_class_covariates")
    histogram = context.get("per_mineral_class_residual_magnitude_buckets")
    clusters = context.get("game_cluster_residual_count_buckets")
    surface_clusters = context.get("game_cluster_surface_context_count_buckets")
    _require(all(isinstance(k, Mapping) for k in
                 (classes, covariates, histogram, clusters)),
             "missing class/stratum/cluster counters")
    _require(set(classes) == set(PUBLISHED_BY_MINERAL),
             "unexpected mineral class coverage")
    _require(set(covariates) == set(PUBLISHED_BY_MINERAL),
             "missing per-mineral covariates")
    _require(set(histogram) == set(PUBLISHED_BY_MINERAL),
             "missing per-mineral magnitude buckets")
    _require(set(clusters) == set(MINERAL_CLASSES),
             "missing class game cluster distributions")
    per_mineral: dict[str, Any] = {}
    aggregated_counts = Counter()
    aggregate_strata: dict[str, Counter[str]] = defaultdict(Counter)
    residual_magnitudes: Counter[str] = Counter()
    for mineral in sorted(PUBLISHED_BY_MINERAL):
        expected = dict(zip(MINERAL_CLASSES, PUBLISHED_BY_MINERAL[mineral]))
        raw = classes[mineral]
        _require(isinstance(raw, Mapping), "invalid mineral class")
        for cls, count in expected.items():
            _require(_count(raw, cls) == count, "class total differs from published cohort")
            aggregated_counts[cls] += count

            c = covariates[mineral].get(cls, {})
            h = histogram[mineral].get(cls, {})
            _require(isinstance(c, Mapping) and isinstance(h, Mapping),
                     "expected aggregate class covariate/bins")
            row = {field: _count(c, field) for field in SELECTED_COVARIATES}
            _require(all(v <= count for k, v in row.items() if
                         k != "one_ship_opposite_cargo_delta_candidate"),
                     "covariate count exceeds class size")
            # One exactly opposite ship is counted at most once per
            # planet-mineral comparison, never as an order proof.
            _require(row["one_ship_opposite_cargo_delta_candidate"] <= count,
                     "cargo candidate exceeds class size")
            _require(row["owner_ship_observed_at_site_both"] <=
                     row["owner_ship_section_pair_qualified"] <=
                     row["planet_coordinates_qualified"] <= count,
                     "invalid ship context denominator")
            _require(row["opposite_cargo_ship_both_freshness_explicit"] +
                     row["opposite_cargo_ship_freshness_unverified"] <=
                     row["one_ship_opposite_cargo_delta_candidate"],
                     "ship freshness subset exceeds candidates")
            _require(row["observed_starbase_tech_changed"] <=
                     row["owner_starbase_explicit_at_planet_both"],
                     "base tech change without both base observations")
            _require(row["structure_or_tax_controls_changed"] <=
                     row["structure_and_tax_controls_qualified"],
                     "structure changed without observed controls")
            _require(
                row["multiple_ship_cargo_sum_opposite_candidate_not_order"] <=
                row["multiple_co_site_ship_ids_all_cargo_qualified"] <=
                row["same_site_identical_ship_set_all_cargo_qualified"] <=
                row["owner_ship_observed_at_site_both"],
                "multiship cargo candidates exceed observed co-site fleet"
            )
            _require(row["one_ship_opposite_cargo_delta_candidate"] <=
                     row["owner_ship_observed_at_site_both"],
                     "single-ship cargo candidate lacks co-site ship"
            )
            _require(
                row["ownerless_planetlinked_tech_changed_observed"] +
                row["ownerless_planetlinked_tech_unchanged_observed"] <=
                row["ownerless_base_planetlinked_both_not_owner_proof"] <=
                row["planetlinked_base_both_any_owner_provenance"],
                "ownerless starbase link counters conflict"
            )
            _require(row["owner_starbase_explicit_at_planet_both"] <=
                     row["planetlinked_base_both_any_owner_provenance"],
                     "owner-provenance base cannot exceed all planet links"
            )
            _require(row["planetlinked_base_owner_provenance_changed"] <=
                     row["planetlinked_base_both_any_owner_provenance"],
                     "base provenance changed without both planet links")
            _require(row["ABSTAIN_PLANET_COORDS_MISSING"] +
                     row["planet_coordinates_qualified"] == count,
                     "planet coordinates are not partitioned")
            for bucket, amount in h.items():
                _require(isinstance(bucket, str) and
                         bucket in ("0", "1", "2_to_5", "6_to_20",
                                    "21_to_100", "101_to_1000", "over_1000"),
                         "unexpected residual magnitude bucket")
                _require(type(amount) is int and amount >= 0,
                         "invalid magnitude bucket")
            _require(sum(h.values()) == count,
                     "residual histogram denominator mismatch")
            for name, value in row.items():
                aggregate_strata[cls][name] += value
            if cls == "ground_exact_surface_residual":
                residual_magnitudes.update(h)
        per_mineral[mineral] = {
            "both_exact": expected["both_exact"],
            "surface_only_residual": expected["ground_exact_surface_residual"],
            "same_site_owner_ship_both_when_surface_only_residual":
                _count(covariates[mineral].get("ground_exact_surface_residual", {}),
                       "owner_ship_observed_at_site_both"),
            "single_opposite_ship_cargo_candidate_not_proof":
                _count(covariates[mineral].get("ground_exact_surface_residual", {}),
                       "one_ship_opposite_cargo_delta_candidate"),
        }

    _require(aggregated_counts == {
        "both_exact": 11813,
        "ground_exact_surface_residual": 915,
        "surface_exact_ground_residual": 33,
        "neither_exact": 262,
    }, "aggregate mismatch")
    _require(sum(residual_magnitudes.values()) == 915,
             "915 residual magnitude histogram missing observations")
    for cls, buckets in clusters.items():
        _require(isinstance(buckets, Mapping), "invalid game cluster histogram")
        total_games = 0
        for label, count in buckets.items():
            _require(label in (
                "0", "1", "2_to_5", "6_to_20", "21_to_100", "over_100"
            ) and type(count) is int and count >= 0,
                     "invalid game clustering bucket")
            total_games += count
        _require(total_games == 68, "game clustering must cover all 68 selected games")

    expected_metrics = {
        "owner_ship_observed_at_site_both",
        "one_ship_opposite_cargo_delta_candidate",
        "multiple_ship_cargo_sum_opposite_candidate_not_order",
        "ownerless_base_planetlinked_both_not_owner_proof",
        "owner_starbase_explicit_at_planet_both",
    }
    if surface_clusters is not None:
        _require(isinstance(surface_clusters, Mapping) and
                 set(surface_clusters) == expected_metrics,
                 "unexpected per-game surface-context metric coverage")
        for metric, hist in surface_clusters.items():
            _require(isinstance(hist, Mapping), "invalid per-game context bins")
            _require(
                all(bucket in (
                    "0", "1", "2_to_5", "6_to_20", "21_to_100", "over_100"
                ) and type(amount) is int and amount >= 0
                    for bucket, amount in hist.items()) and
                sum(hist.values()) == 68,
                "surface-context per-game bins must cover all baseline68 games"
            )

    def summary_for(cls: str) -> dict[str, Any]:
        n = aggregated_counts[cls]
        cov = aggregate_strata[cls]
        surveyed = cov["owner_ship_section_pair_qualified"]
        site = cov["owner_ship_observed_at_site_both"]
        return {
            "observations": n,
            "planet_coordinate_pairs": cov["planet_coordinates_qualified"],
            "ship_arrays_and_planet_coords_qualified": surveyed,
            "same_site_owner_ship_at_both": site,
            "site_ship_at_both_percent_of_qualified": _portion(site, surveyed),
            "explicit_starbase_at_planet_both":
                cov["owner_starbase_explicit_at_planet_both"],
            "structure_and_tax_controls_qualified":
                cov["structure_and_tax_controls_qualified"],
            "structure_or_tax_controls_changed":
                cov["structure_or_tax_controls_changed"],
            "single_opposite_ship_cargo_delta_candidate":
                cov["one_ship_opposite_cargo_delta_candidate"],
            "opposite_ship_freshness_both_explicit":
                cov["opposite_cargo_ship_both_freshness_explicit"],
            "opposite_ship_freshness_unverified":
                cov["opposite_cargo_ship_freshness_unverified"],
            "ownerless_base_planetlinked_at_both_not_owner_proof":
                cov["ownerless_base_planetlinked_both_not_owner_proof"],
            "planetlinked_base_at_both_any_owner_provenance":
                cov["planetlinked_base_both_any_owner_provenance"],
            "ownerless_planetlinked_base_tech_changed_observed":
                cov["ownerless_planetlinked_tech_changed_observed"],
            "multi_ship_cargo_sum_opposite_candidate_not_order":
                cov["multiple_ship_cargo_sum_opposite_candidate_not_order"],
            "multi_ship_co_site_cargo_qualified":
                cov["multiple_co_site_ship_ids_all_cargo_qualified"],
            "planet_coords_missing": cov["ABSTAIN_PLANET_COORDS_MISSING"],
            "ship_section_missing_after_coordinates_known":
                cov["ABSTAIN_SHIP_SECTION_MISSING_ONE_OR_BOTH"],
        }

    return {
        "schema": SCHEMA,
        "status": "DESCRIPTIVE_M2_SURFACE_RESIDUAL_CONTEXT_NOT_HOST_CAUSAL",
        "source": {
            "corpus_sha256": EXPECTED_DB_SHA,
            "frozen_selection_sha256": EXPECTED_FROZEN_SAMPLE_SHA,
            "baseline_games": 68, "heldout_entity_games": 0,
        },
        "residual_classes_all_minerals": dict(sorted(aggregated_counts.items())),
        "per_mineral": per_mineral,
        "by_outcome": {
            "both_exact": summary_for("both_exact"),
            "ground_exact_surface_residual": summary_for(
                "ground_exact_surface_residual"
            ),
            "surface_exact_ground_residual": summary_for(
                "surface_exact_ground_residual"
            ),
            "neither_exact": summary_for("neither_exact"),
        },
        "surface_only_residual_magnitude_buckets":
            dict(sorted(residual_magnitudes.items())),
        "game_cluster_residual_count_buckets": clusters,
        "game_cluster_surface_context_count_buckets": surface_clusters,
        "evidence_limits": {
            "single_opposite_cargo_candidate_is_executed_transfer": False,
            "same_site_ship_observation_is_independent_causality": False,
            "absent_owner_ships_exclude_unseen_actions": False,
            "rate_differences_are_independent_statistical_inference": False,
            "NuHost_order_execution_verified": False,
        },
    }
